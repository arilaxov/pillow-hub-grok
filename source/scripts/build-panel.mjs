#!/usr/bin/env node
/* Rebuilds public/downloads/Pillow-v192.zip with the Pillow Hub bridge, without unpacking to disk:
   - host/pillow.jsx gets the shared ExtendScript runtime from public/modules/ae-bridge.mjs
   - index.html gets the "Import from Pillow Hub" block in Music, js/hub-import.js and its CSS
   - the panel version is set to PANEL_VERSION below.
   Idempotent: run it again after changing ae-bridge.mjs. Unchanged files are copied byte for byte. */
import fs from 'node:fs';
import path from 'node:path';
import zlib from 'node:zlib';
import {fileURLToPath} from 'node:url';
import {AE_RUNTIME} from '../public/modules/ae-bridge.mjs';

export const PANEL_VERSION = '1.1.1';
const CRC = (() => { const t = new Uint32Array(256); for (let n = 0; n < 256; n++) { let c = n; for (let k = 0; k < 8; k++) c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1; t[n] = c >>> 0; } return t; })();
export function crc32(data) { let c = 0xffffffff; for (let i = 0; i < data.length; i++) c = CRC[(c ^ data[i]) & 0xff] ^ (c >>> 8); return (c ^ 0xffffffff) >>> 0; }
const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const zipPath = process.argv[2] || path.join(root, 'public/downloads/Pillow-v192.zip');
const src = name => fs.readFileSync(path.join(root, 'scripts/panel', name), 'utf8');

export function readZip(buf) {
  let eocd = buf.length - 22; while (eocd >= 0 && buf.readUInt32LE(eocd) !== 0x06054b50) eocd--;
  if (eocd < 0) throw new Error('Not a ZIP file');
  const count = buf.readUInt16LE(eocd + 10); let p = buf.readUInt32LE(eocd + 16); const entries = [];
  for (let i = 0; i < count; i++) {
    if (buf.readUInt32LE(p) !== 0x02014b50) throw new Error('Bad central directory');
    const e = { madeBy: buf.readUInt16LE(p + 4), flags: buf.readUInt16LE(p + 8), method: buf.readUInt16LE(p + 10), time: buf.readUInt16LE(p + 12), date: buf.readUInt16LE(p + 14),
      crc: buf.readUInt32LE(p + 16), csize: buf.readUInt32LE(p + 20), size: buf.readUInt32LE(p + 24), internal: buf.readUInt16LE(p + 36), external: buf.readUInt32LE(p + 38) };
    const nl = buf.readUInt16LE(p + 28), xl = buf.readUInt16LE(p + 30), cl = buf.readUInt16LE(p + 32), off = buf.readUInt32LE(p + 42);
    e.name = buf.toString('utf8', p + 46, p + 46 + nl);
    const start = off + 30 + buf.readUInt16LE(off + 26) + buf.readUInt16LE(off + 28);
    e.raw = buf.subarray(start, start + e.csize);
    entries.push(e); p += 46 + nl + xl + cl;
  }
  return entries;
}
export const entryText = e => (e.method === 8 ? zlib.inflateRawSync(e.raw) : e.raw).toString('utf8');
function setData(e, text) {
  const data = Buffer.from(text, 'utf8'); e.size = data.length; e.crc = crc32(data);
  e.raw = zlib.deflateRawSync(data, { level: 9 }); e.method = 8; e.csize = e.raw.length; e.flags &= ~0x0008; e.flags |= 0x0800;
  const d = new Date(); e.time = (d.getHours() << 11) | (d.getMinutes() << 5) | (d.getSeconds() >> 1); e.date = ((d.getFullYear() - 1980) << 9) | ((d.getMonth() + 1) << 5) | d.getDate();
}
export function writeZip(entries) {
  const parts = [], central = []; let offset = 0;
  for (const e of entries) {
    const name = Buffer.from(e.name, 'utf8'), h = Buffer.alloc(30);
    h.writeUInt32LE(0x04034b50, 0); h.writeUInt16LE(20, 4); h.writeUInt16LE(e.flags & ~0x0008, 6); h.writeUInt16LE(e.method, 8); h.writeUInt16LE(e.time, 10); h.writeUInt16LE(e.date, 12);
    h.writeUInt32LE(e.crc, 14); h.writeUInt32LE(e.csize, 18); h.writeUInt32LE(e.size, 22); h.writeUInt16LE(name.length, 26);
    parts.push(h, name, e.raw);
    const c = Buffer.alloc(46);
    c.writeUInt32LE(0x02014b50, 0); c.writeUInt16LE(e.madeBy, 4); c.writeUInt16LE(20, 6); c.writeUInt16LE(e.flags & ~0x0008, 8); c.writeUInt16LE(e.method, 10); c.writeUInt16LE(e.time, 12); c.writeUInt16LE(e.date, 14);
    c.writeUInt32LE(e.crc, 16); c.writeUInt32LE(e.csize, 20); c.writeUInt32LE(e.size, 24); c.writeUInt16LE(name.length, 28); c.writeUInt16LE(e.internal, 36); c.writeUInt32LE(e.external, 38); c.writeUInt32LE(offset, 42);
    central.push(c, name); offset += 30 + name.length + e.raw.length;
  }
  const cd = Buffer.concat(central), end = Buffer.alloc(22);
  end.writeUInt32LE(0x06054b50, 0); end.writeUInt16LE(entries.length, 8); end.writeUInt16LE(entries.length, 10); end.writeUInt32LE(cd.length, 12); end.writeUInt32LE(offset, 16);
  return Buffer.concat([...parts, cd, end]);
}

export function patchPanel(entries) {
  const find = name => entries.find(e => e.name === name) || (() => { throw new Error('Missing ' + name); })();
  const edit = (name, fn) => { const e = find(name), before = entryText(e), after = fn(before); if (after !== before) setData(e, after); };
  // 1. host: shared runtime between markers
  edit('Pillow/host/pillow.jsx', s => {
    const a = s.indexOf('/* >>> Pillow Hub bridge runtime'), b = s.indexOf('/* <<< Pillow Hub bridge runtime */');
    const block = '\n\n/* ─── Pillow Hub bridge (generated by scripts/build-panel.mjs from public/modules/ae-bridge.mjs) ─── */\n' + AE_RUNTIME + '\n';
    if (a >= 0 && b > a) { const start = s.lastIndexOf('\n\n/* ─── Pillow Hub bridge', a); return s.slice(0, start >= 0 ? start : a) + block.replace(/\n$/, '') + s.slice(b + '/* <<< Pillow Hub bridge runtime */'.length); }
    return s.replace(/\s*$/, '') + block;
  });
  // 2. index.html: import block after the Music explainer, script after music.js
  edit('Pillow/index.html', s => {
    const block = src('hub-import.html').replace(/\s+$/, '');
    const a = s.indexOf('          <!-- PILLOW HUB IMPORT -->');
    if (a >= 0) { const b = s.indexOf('</div>', s.indexOf('id="hub-import-input"')) + 6; s = s.slice(0, a) + block + s.slice(b); }
    else {
      const music = s.indexOf('<section id="pane-music"'), close = s.indexOf('</section>', music);
      if (music < 0 || close < 0) throw new Error('Music pane not found');
      s = s.slice(0, close).replace(/\s*$/, '\n\n') + block + '\n        ' + s.slice(close);
    }
    if (!s.includes('js/hub-import.js')) s = s.replace('<script src="js/music.js"></script>', '<script src="js/music.js"></script>\n  <script src="js/hub-import.js"></script>');
    return s;
  });
  // 3. CSS
  edit('Pillow/css/panel.css', s => {
    const css = src('hub-import.css'), a = s.indexOf('\n/* ─── Import from Pillow Hub');
    return (a >= 0 ? s.slice(0, a) : s.replace(/\s*$/, '\n')) + css;
  });
  // 4. new script file
  let js = entries.find(e => e.name === 'Pillow/js/hub-import.js');
  if (!js) { const like = find('Pillow/js/music.js'); js = { ...like, name: 'Pillow/js/hub-import.js' }; entries.splice(entries.indexOf(like) + 1, 0, js); js.raw = Buffer.alloc(0); }
  if (js.raw.length === 0 || entryText(js) !== src('hub-import.js')) setData(js, src('hub-import.js'));
  // 5. version
  edit('Pillow/CSXS/manifest.xml', s => s.replace(/ExtensionBundleVersion="[^"]*"/, `ExtensionBundleVersion="${PANEL_VERSION}"`).replace(/(<Extension Id="com\.pillow\.panel\.main" Version=")[^"]*"/, `$1${PANEL_VERSION}"`));
  edit('Pillow/js/panel.js', s => s.replace(/var PILLOW_VERSION = "[^"]*";/, `var PILLOW_VERSION = "${PANEL_VERSION}";`));
  return entries;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === path.resolve(process.argv[1])) {
  const before = fs.readFileSync(zipPath), entries = patchPanel(readZip(before)), after = writeZip(entries);
  fs.writeFileSync(zipPath, after);
  console.log(`Pillow panel ${PANEL_VERSION} → ${path.relative(root, zipPath)} (${entries.length} entries, ${(after.length / 1048576).toFixed(2)} MB)`);
}
